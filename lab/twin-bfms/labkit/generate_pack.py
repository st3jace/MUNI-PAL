def _print_result(res: GenerateResult) -> None:
    print(f"{res.deal_id}: {res.files_written} files ({res.intake_files} intake, {res.vault_files} vault) -> {res.pack_root}")
    print(f"  PACK-MANIFEST.json sha256 {res.manifest_sha256}")
    for entry in res.absent_by_scenario:
        print("  absent_by_scenario: " + json.dumps(entry, sort_keys=True))
    if res.intake_paths_unknown:
        print(f"  intake paths with no line (expected unknown): {res.intake_paths_unknown}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--scenario", help="scenario json (deal-v0 + lab block)")
    parser.add_argument("--out", help="output directory (pack goes to <out>/<deal_id>); default packs/")
    parser.add_argument("--all", action="store_true", help="generate the three committed scenarios and packs/_pins.json")
    parser.add_argument("--bondi-reference", action="store_true", help="write fixtures/bondi-reference/{format.json,PROVENANCE.md}")
    args = parser.parse_args(argv)
    try:
        if args.bondi_reference:
            fmt_file, prov_file = write_bondi_reference()
            print(f"wrote {fmt_file.path} ({fmt_file.sha256}) and {prov_file.path}")
        if args.all:
            shas: dict[str, str] = {}
            for deal_id in COMMITTED_SCENARIOS:
                res = generate(scenario_mod.SCENARIOS_DIR / f"{deal_id}.synthetic.json", args.out)
                _print_result(res)
                shas[deal_id] = res.manifest_sha256
            if args.out is None:
                pins = write_pins(shas)
                print(f"wrote {pins.path} ({pins.sha256})")
        elif args.scenario:
            _print_result(generate(args.scenario, args.out))
        elif not args.bondi_reference:
            parser.error("--scenario, --all or --bondi-reference required")
    except (PackError, ProvenanceViolation, scenario_mod.ScenarioError) as exc:
        print(f"REFUSED: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())


