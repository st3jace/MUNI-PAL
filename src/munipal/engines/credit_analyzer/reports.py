"""Credit Analyzer report generation — produces Markdown + JSON reports."""

from __future__ import annotations

import json
import logging
from datetime import datetime, timezone
from pathlib import Path

from .models import (
    BondSizingResult,
    CreditAnalysisResult,
    FiveCsAssessment,
)

logger = logging.getLogger("credit_analyzer.reports")

DEFAULT_REPORT_DIR = Path("reports/credit_analyzer")


def _ensure_dir(path: Path) -> Path:
    path.mkdir(parents=True, exist_ok=True)
    return path


def _ts() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")


def _slug(name: str) -> str:
    return name.lower().replace(" ", "_").replace("/", "_")[:30]


# ---------------------------------------------------------------------------
# 5 Cs Report
# ---------------------------------------------------------------------------

def generate_five_cs_report(
    result: FiveCsAssessment,
    output_dir: Path | None = None,
) -> tuple[Path, Path]:
    out = _ensure_dir(output_dir or DEFAULT_REPORT_DIR)
    ts = _ts()
    slug = _slug(result.project_name)

    lines = [
        f"# 5 Cs Credit Assessment: {result.project_name}",
        f"",
        f"**Generated:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
        f"**Composite Score:** {result.composite_score:.1f}/100 ({result.composite_grade})",
        f"**Recommendation:** {result.recommendation.replace('_', ' ').title()}",
        f"",
        f"## Summary",
        f"",
        f"| Dimension | Weight | Score | Grade | Weighted |",
        f"|-----------|-------:|------:|:-----:|---------:|",
    ]

    for cs in [result.character, result.capacity, result.capital, result.collateral, result.conditions]:
        lines.append(
            f"| {cs.dimension} | {cs.weight:.0%} | {cs.score:.0f} | {cs.grade} | {cs.weighted_score:.1f} |"
        )
    lines.append(f"| **Composite** | **100%** | | **{result.composite_grade}** | **{result.composite_score:.1f}** |")
    lines.append("")

    for cs in [result.character, result.capacity, result.capital, result.collateral, result.conditions]:
        lines.append(f"## {cs.dimension} ({cs.score:.0f}/100, {cs.grade})")
        lines.append("")
        if cs.findings:
            lines.append("**Findings:**")
            for f in cs.findings:
                lines.append(f"- {f}")
            lines.append("")
        if cs.risks:
            lines.append("**Risks:**")
            for r in cs.risks:
                lines.append(f"- {r}")
            lines.append("")
        if cs.mitigants:
            lines.append("**Mitigants:**")
            for m in cs.mitigants:
                lines.append(f"- {m}")
            lines.append("")

    if result.conditions_for_approval:
        lines.append("## Conditions for Approval")
        lines.append("")
        for i, c in enumerate(result.conditions_for_approval, 1):
            lines.append(f"{i}. {c}")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by Muni-Pal Credit Analyzer v0.1.0*")

    md_path = out / f"five_cs_{slug}_{ts}.md"
    md_path.write_text("\n".join(lines), encoding="utf-8")

    json_path = out / f"five_cs_{slug}_{ts}.json"
    json_path.write_text(result.model_dump_json(indent=2), encoding="utf-8")

    return md_path, json_path


