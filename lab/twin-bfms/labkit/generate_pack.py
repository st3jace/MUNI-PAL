_extractor = RulesBasedExtractor()


def schema_for(path: str) -> dict[str, Any]:
    return _SCHEMA_BY_PATH.get(path, {"path": path, "value_type": "string"})


def labels_for(path: str) -> tuple[str, ...]:
    return _extractor._labels_for_path(path, schema_for(path))


def label_for(path: str) -> str:
    """The FIRST extractor label for `path`, capitalised (BUILD-SPEC 4.1)."""
    first = labels_for(path)[0]
    return first[0].upper() + first[1:]


def expected_value(path: str, value: str) -> Any:
    if path in INT_COMPARED_PATHS:
        return int(re.sub(r"[^\d]", "", value))
    return value


def _extract_one(text: str, path: str) -> Any:
    facts = _extractor.extract([{"id": "self-check", "text_content": text}], [path])
    return facts[0].value if facts else None


def order_lines(paths: list[str], facts: dict[str, str], fixed_prefix: list[str]) -> list[str]:
    """Order `paths` so each path's own line is the first match for its labels.

    Constraint: if the line of A yields a WRONG value for B, B's line must precede A's.
    Kahn's algorithm with the scenario order as the tie-break; a cycle refuses the pack.
    `fixed_prefix` (envelope + legend) cannot be reordered, so it must yield nothing wrong.
    """
    line_of = {p: f"{label_for(p)}: {facts[p]}" for p in paths}
    for p in paths:
        for fixed in fixed_prefix:
            got = _extract_one(fixed, p)
            if got is not None and got != expected_value(p, facts[p]):
                raise PackError(f"fixed line {fixed!r} would hijack {p} (got {got!r})")
    must_precede: dict[str, set[str]] = {p: set() for p in paths}  # b -> {a}: b before a
    for a in paths:
        for b in paths:
            if a == b:
                continue
            got = _extract_one(line_of[a], b)
            if got is not None and got != expected_value(b, facts[b]):
                must_precede[b].add(a)
    ordered: list[str] = []
    remaining = list(paths)
    while remaining:
        ready = [p for p in remaining if not any(q in remaining for q in _predecessors(p, must_precede))]
        if not ready:
            raise PackError(f"label collision cycle among {remaining}; cannot order lines")
        nxt = ready[0]
        ordered.append(nxt)
        remaining.remove(nxt)
    return ordered


def _predecessors(p: str, must_precede: dict[str, set[str]]) -> set[str]:
    return {b for b, afters in must_precede.items() if p in afters}


@dataclass
class IntakeFile:
    order: int
    artifact_key: str
    display_name: str
    requirement_level: str
    folder: str
    relpath: str
    paths: list[str]
    labels: dict[str, str]
    body_lines: list[str]
    text: str = ""
    sha256: str = ""


def readability_check(files: list[IntakeFile], facts: dict[str, str]) -> list[str]:
    """Per-artifact extractor round-trip (M4). Empty list == every path round-trips."""
    problems: list[str] = []
    all_labels = {lbl for f in files for p in f.paths for lbl in labels_for(p)}
    env_keys = ("source", "generator_version", "lab_version", "scenario_id", "seed", "sha256_body", "created_from")
    for key in env_keys:
        norm = _extractor._normalize_label(key)
        for lbl in all_labels:
            if lbl in norm:
                problems.append(f"envelope key {key!r} contains target label {lbl!r}")
    for f in files:
        got = _extractor.extract([{"id": f.relpath, "text_content": f.text}], f.paths)
        by_path: dict[str, list[Any]] = {}
        for fact in got:
            by_path.setdefault(fact.schema_path, []).append(fact.value)
        for p in f.paths:
            vals = by_path.get(p, [])
            want = expected_value(p, facts[p])
            if len(vals) != 1:
                problems.append(f"{f.relpath}: {p} yielded {len(vals)} facts, want 1")
            elif vals[0] != want:
                problems.append(f"{f.relpath}: {p} round-trips to {vals[0]!r}, want {want!r}")
    return problems


def _build_intake(sc: scenario_mod.Scenario, envelope: Envelope) -> list[IntakeFile]:
    playbook = build_pilot_onboarding_workflow(str(sc.lab["sector_playbook_key"])).playbook
    by_key = {a.artifact_key: a for a in playbook.required_artifacts}
    facts = sc.intake_facts
    files: list[IntakeFile] = []
    order = 0
    for artifact_key, paths in sc.intake_docs.items():
        if artifact_key not in by_key:
            raise PackError(f"intake_docs names {artifact_key!r}, not a housing RequiredArtifact")
        folder = FOLDER_BY_ARTIFACT.get(artifact_key)
        if folder is None or folder not in _OPERATOR_WORKSPACE_FOLDERS:
            raise PackError(f"no operator workspace folder for {artifact_key!r}")
        art = by_key[artifact_key]
        relpath = f"{INTAKE_DIR}/{folder}/{artifact_key}.txt"
        env = envelope.model_copy(
            update={"created_from": [f"scenario:{sc.deal_id}#lab.intake_docs.{artifact_key}"]}
        )
        fixed_prefix = [f"# {line}" for line in env.as_lines()] + [law.LEGEND]
        ordered = order_lines(list(paths), facts, fixed_prefix)
        labels = {p: label_for(p) for p in ordered}
        body_lines: list[str] = []
        seen: set[str] = set()
        for p in ordered:
            line = f"{labels[p]}: {facts[p]}"
            if line in seen:
                continue  # identical label+value (F5 twin spellings) -> one line serves both
            seen.add(line)
            body_lines.append(line)
        if artifact_key == "rent_roll_operating":
            for row in RENT_ROLL_TABLE:
                for p in ordered:
                    if _extract_one(row, p) is not None:
                        raise PackError(f"pipe row {row!r} carries a target label for {p}")
            body_lines += ["", *RENT_ROLL_TABLE]
        order += 1
        files.append(
            IntakeFile(
                order=order,
                artifact_key=artifact_key,
                display_name=art.display_name,
                requirement_level=art.requirement_level,
                folder=folder,
                relpath=relpath,
                paths=list(ordered),
                labels=labels,
                body_lines=body_lines,
            )
        )
    for f in files:
        env = envelope.model_copy(
            update={"created_from": [f"scenario:{sc.deal_id}#lab.intake_docs.{f.artifact_key}"]}
        )
        body = "\n".join(f.body_lines)
        env = env.model_copy(update={"sha256_body": sha256_text(body)})
        f.text = "\n".join([f"# {line}" for line in env.as_lines()] + [law.LEGEND] + f.body_lines) + "\n"
    problems = readability_check(files, facts)
    if problems:
        raise PackError("readability self-check failed; refusing to write: " + "; ".join(problems))
    return files


def _document_request_rows(sc: scenario_mod.Scenario, files: list[IntakeFile]) -> list[dict[str, str]]:
    workflow = build_pilot_onboarding_workflow(str(sc.lab["sector_playbook_key"]))
    playbook = workflow.playbook
    key_by_display = {a.display_name: a.artifact_key for a in playbook.required_artifacts}
    file_by_key = {f.artifact_key: f for f in files}
    rows: list[dict[str, str]] = []
    for item in workflow.document_request_list:
        m = re.match(r"^(.*) \((required|recommended)\)$", item)
        if not m or m.group(1) not in key_by_display:
            raise PackError(f"document_request_list entry {item!r} maps to no required_artifacts row")
        key = key_by_display[m.group(1)]
        f = file_by_key.get(key)
        if f is not None:
            status = f"present ({f.relpath})"
        elif key in sc.dropped_artifacts:
            status = "absent_by_scenario (knob drop_required_artifact)"
        else:
            status = "absent (not carried by scenario)"
        rows.append({"request": item, "artifact_key": key, "level": m.group(2), "status": status})
    return rows


