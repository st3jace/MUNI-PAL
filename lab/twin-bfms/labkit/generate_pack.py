_VIA_TOKEN_RE = re.compile(r" via " + law.EMMA_WORD.pattern)
_PAREN_TOKEN_RE = re.compile(r"\s*\(" + law.EMMA_WORD.pattern + r"\)")


def scrub_platform_token(text: str) -> str:
    """Remove ` via <token>` and ` (<token>)`; refuse if the token survives."""
    out = _PAREN_TOKEN_RE.sub("", _VIA_TOKEN_RE.sub("", text))
    if law.EMMA_WORD.search(out):
        raise PackError(f"platform token survives scrub: {text!r}")
    return out


