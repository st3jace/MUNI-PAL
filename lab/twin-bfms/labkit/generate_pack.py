def _literal_assign(tree: ast.Module, name: str) -> Any:
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise PackError(f"generate.py: no module-level literal assignment {name}")


def _fieldnames(tree: ast.Module) -> list[str]:
    for node in ast.walk(tree):
        if isinstance(node, ast.keyword) and node.arg == "fieldnames":
            return list(ast.literal_eval(node.value))
    raise PackError("generate.py: DictWriter fieldnames not found")


def transcribe_bondi_format(generate_py: Path) -> dict[str, Any]:
    """Transcribe the emission format from generate.py by ast (never executed)."""
    source = generate_py.read_bytes()
    tree = ast.parse(source.decode("utf-8"))
    core = _literal_assign(tree, "STATION_EVENTS_CORE")
    by_pole = _literal_assign(tree, "STATION_EVENTS_BY_POLE")
    post = _literal_assign(tree, "STATION_EVENTS_POST")
    poles = list(_literal_assign(tree, "SALE_POLES"))
    header = _fieldnames(tree)
    if tuple(header) != law.EVENT_LOG_HEADER:
        raise PackError(f"generate.py header {header} != law.EVENT_LOG_HEADER")
    constants = {n.value for n in ast.walk(tree) if isinstance(n, ast.Constant) and isinstance(n.value, str)}
    missing = [s for s in law.BONDI_EVENT_STATUSES if s not in constants]
    if missing:
        raise PackError(f"generate.py does not spell status(es) {missing}")
    rows = lambda items: [{"station": s, "event": e, "actor_role": r} for s, e, r in items]  # noqa: E731
    stations = sorted({s for s, _e, _r in [*core, *post, *(x for rs in by_pole.values() for x in rs)]})
    if stations != sorted(law.BONDI_STATIONS):
        raise PackError(f"generate.py stations {stations} != law.BONDI_STATIONS")
    return {
        "source_path_windows": BONDI_GENERATE_WINDOWS_PATH,
        "source_path_wsl": str(scenario_mod.bondi_root() / BONDI_GENERATE_REL),
        "source_sha256": sha256_bytes(source),
        "transcribed_on": TRANSCRIPTION_DATE,
        "method": "ast.literal_eval of the module-level constants STATION_EVENTS_CORE, STATION_EVENTS_BY_POLE, STATION_EVENTS_POST, SALE_POLES and the DictWriter fieldnames; generate.py was never executed and is never imported",
        "not_transcribed": "the date offsets (SCENARIO DRESSING) and the Form 8038 due-date helper: the lab never computes a date",
        "event_log_header": header,
        "stations": list(law.BONDI_STATIONS),
        "sale_poles": poles,
        "station_events_core": rows(core),
        "station_events_by_pole": {pole: rows(items) for pole, items in by_pole.items()},
        "station_events_post": rows(post),
        "event_statuses": list(law.BONDI_EVENT_STATUSES),
        "hold_statuses": list(law.HOLD_STATUSES),
        "constraint_statuses": list(law.CONSTRAINT_STATUSES),
        "lab_extension_events": sorted(law.LAB_EXTENSION_EVENTS),
    }


