def _emma_allowance(relpath: str) -> tuple[int, str | None]:
    for allowed_rel, heading, count in law.EMMA_ALLOWLIST:
        if allowed_rel == relpath:
            return count, heading
    return 0, None


def _assert_token_under_heading(text: str, heading: str, count: int, where: str) -> None:
    lines = text.split("\n")
    start = next((i for i, line in enumerate(lines) if line.startswith(heading)), None)
    if start is None:
        raise PackError(f"{where}: heading starting {heading!r} not found")
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    inside = sum(len(law.EMMA_WORD.findall(line)) for line in lines[start + 1 : end])
    if inside != count:
        raise PackError(f"{where}: {inside} platform-token line(s) under {heading!r}, pinned {count}")


def _vault_name_map(bf: ModuleType, run: ModuleType) -> dict[str, tuple[str, str, str, dict[str, str]]]:
    """rendered evidence-file stem -> (obligation_id, pattern, due ISO, tokens).

    This is the demo's OWN labelling: `approved-inputs.csv` `evidence_pattern` rendered
    with `run.py::period_tokens` for each approved due date. It is not a computed
    obligation date; the due dates are the counsel-approved literals in the csv.
    """
    from datetime import date as _date

    out: dict[str, tuple[str, str, str, dict[str, str]]] = {}
    for row in bf.APPROVED:
        rec = dict(zip(bf.APPROVED_FIELDS, row, strict=True))
        pattern = rec["evidence_pattern"]
        if not pattern:
            continue
        for due in [d for d in rec["due_dates_approved"].split(";") if d.strip()]:
            tokens = run.period_tokens(_date.fromisoformat(due))
            out[pattern.format(**tokens)] = (rec["obligation_id"], pattern, due, tokens)
    return out


def generate(scenario_path: Path | str, out_dir: Path | str | None = None) -> GenerateResult:
    """Generate `packs/<deal_id>/` (or `<out_dir>/<deal_id>/`) from a scenario file."""
    sc = scenario_mod.load(scenario_path)
    table_problems = names_mod.check_table()
    if table_problems:
        raise PackError("name table problems: " + "; ".join(table_problems))
    bf, run = demo_modules()
    pack_root = (Path(out_dir) if out_dir is not None else PACKS_DIR) / sc.deal_id
    if pack_root.exists():
        shutil.rmtree(pack_root)
    pack_root.mkdir(parents=True)
    envelope = Envelope(scenario_id=sc.deal_id, seed=sc.seed)
    manifest = PackManifest(pack_root, envelope)

    # 1. intake -------------------------------------------------------------------
    files = _build_intake(sc, envelope)
    for f in files:
        env = envelope.model_copy(update={"created_from": [f"scenario:{sc.deal_id}#lab.intake_docs.{f.artifact_key}"]})
        written = write_txt(pack_root / f.relpath, "\n".join(f.body_lines), env, manifest=manifest)
        f.sha256 = written.sha256
        if (pack_root / f.relpath).read_text(encoding="utf-8") != f.text:
            raise PackError(f"{f.relpath}: written text differs from the self-checked text")
    request_rows = _document_request_rows(sc, files)
    checklist_lines = [
        "# Document request checklist (housing sector playbook)",
        "",
        f"Generated from `build_pilot_onboarding_workflow({sc.lab['sector_playbook_key']!r}).document_request_list`"
        " (src/munipal/services/pilot_onboarding.py:202-207) mapped through"
        " `playbook.required_artifacts[*].display_name -> artifact_key`"
        " (src/munipal/services/sector_playbooks.py::_HOUSING_ARTIFACTS).",
        "",
        "| # | Requested document | Level | artifact_key | status in this pack |",
        "|---|---|---|---|---|",
    ]
    for i, row in enumerate(request_rows, start=1):
        checklist_lines.append(f"| {i} | {row['request']} | {row['level']} | `{row['artifact_key']}` | {row['status']} |")
    write_md(
        pack_root / INTAKE_DIR / WELCOME_FOLDER / "document-request-checklist.md",
        "\n".join(checklist_lines),
        envelope.model_copy(update={"created_from": ["src/munipal/services/pilot_onboarding.py::build_pilot_onboarding_workflow('housing').document_request_list"]}),
        manifest=manifest,
    )
    intake_manifest = {
        "upload_order": [
            {
                "order": f.order,
                "path": f.relpath,
                "artifact_key": f.artifact_key,
                "display_name": f.display_name,
                "requirement_level": f.requirement_level,
                "folder": f.folder,
                "expected_paths": f.paths,
                "labels": f.labels,
                "sha256": f.sha256,
                "content_type": "text/plain",
            }
            for f in files
        ],
        "dropped": [
            {
                "artifact_key": key,
                "status": "absent_by_scenario",
                "reason": "knob drop_required_artifact",
                "paths": list(sc.dropped_intake_paths),
            }
            for key in sc.dropped_artifacts
        ],
        "self_check": {
            "mode": "per-artifact (one extraction job per intake artifact; target_schema_paths = that artifact's expected_paths)",
            "extractor": "munipal.services.extraction.rules_based_extractor.RulesBasedExtractor (offline, no LLM)",
            "chunk_text": "the whole file as uploaded, envelope and legend lines included",
            "int_compared_paths": sorted(INT_COMPARED_PATHS),
            "result": "pass",
        },
        "workspace_folders": list(_OPERATOR_WORKSPACE_FOLDERS),
    }
    write_json(
        pack_root / INTAKE_DIR / "intake-manifest.json",
        intake_manifest,
        envelope.model_copy(update={"created_from": [f"scenario:{sc.deal_id}#lab.intake_docs"]}),
        manifest=manifest,
    )
    for key in sc.dropped_artifacts:
        manifest.add_absent(artifact_key=key, reason="knob drop_required_artifact")

    # 2. closing documents (the single copy; reused demo constants) --------------------
    for name, body in bf.DOCUMENTS.items():
        relpath = f"{CLOSING_DIR}/{name}"
        count, heading = _emma_allowance(relpath)
        written = write_md(
            pack_root / relpath,
            body,
            envelope.model_copy(update={"created_from": [f"fulfillment/demo/build_fixtures.py::DOCUMENTS[{name!r}]"]}),
            emma_allowed=count,
            manifest=manifest,
        )
        if heading is not None:
            _assert_token_under_heading(written.path.read_text(encoding="utf-8"), heading, count, relpath)
    for doc_type, reason in STANDARD_DOCS_NOT_CARRIED:
        manifest.add_absent(type=doc_type, reason=reason)

    # 3. post-close evidence ---------------------------------------------------------
    approved_rows: list[dict[str, str]] = []
    for row in bf.APPROVED:
        rec = dict(zip(bf.APPROVED_FIELDS, row, strict=True))
        rec["obligation"] = scrub_platform_token(rec["obligation"])
        rec["recipient"] = scrub_platform_token(rec["recipient"])
        approved_rows.append(rec)
    write_csv(
        pack_root / POST_CLOSE_DIR / "approved-inputs.csv",
        list(bf.APPROVED_FIELDS),
        approved_rows,
        envelope.model_copy(update={"created_from": ["fulfillment/demo/build_fixtures.py::APPROVED (columns obligation, recipient scrubbed of the MSRB platform token)"]}),
        manifest=manifest,
    )
    write_md(
        pack_root / POST_CLOSE_DIR / bf.REF,
        bf.APPROVAL_NOTE,
        envelope.model_copy(update={"created_from": ["fulfillment/demo/build_fixtures.py::APPROVAL_NOTE"]}),
        manifest=manifest,
    )
    name_map = _vault_name_map(bf, run)
    late_afs = bool(sc.lab.get("knobs", {}).get("late_afs"))
    uncarried_fys = {
        str(a["fy"]) for a in (sc.data.get("disclosure") or {}).get("afs") or [] if not a.get("posted")
    }
    vault_written = 0
    for fname, title, filed, recipient in bf.VAULT:
        stem = fname[:-4] if fname.endswith(".txt") else fname
        if stem not in name_map:
            raise PackError(f"vault file {fname!r} matches no rendered evidence_pattern")
        ob_id, pattern, due, tokens = name_map[stem]
        if late_afs and pattern in AFS_LINKED_PATTERNS and tokens["fy"] in uncarried_fys:
            manifest.add_absent(
                vault_file=f"{POST_CLOSE_DIR}/{VAULT_DIR}/{stem}.txt",
                obligation_id=ob_id,
                reason="knob late_afs; afs posting not carried",
            )
            continue
        write_vault_txt(
            pack_root / POST_CLOSE_DIR / VAULT_DIR / f"{stem}.txt",
            f"SYNTHETIC EVIDENCE FILE - {title}",
            f"Filed/delivered: {filed}\nRecipient: {scrub_platform_token(recipient)}",
            envelope.model_copy(
                update={
                    "created_from": [
                        f"fulfillment/demo/build_fixtures.py::VAULT[{fname!r}]",
                        f"approved-inputs.csv:{ob_id} evidence_pattern {pattern!r} rendered with run.py::period_tokens for approved due {due}",
                    ]
                }
            ),
            manifest=manifest,
        )
        vault_written += 1
    demo_stems = {fname[:-4] for fname, *_ in bf.VAULT}
    for stem, (ob_id, pattern, due, _tokens) in sorted(name_map.items()):
        if stem in demo_stems:
            continue
        if pattern.startswith("rebate-calc-"):
            reason = f"first Computation Date {due[:4]}; asof {sc.asof}"
        elif due <= sc.asof:
            reason = "absent in the demo fixture set (build_fixtures.VAULT); the base's evidence-missing row"
        else:
            continue  # not yet due at asof: nothing is absent, nothing is said
        manifest.add_absent(vault_file=f"{POST_CLOSE_DIR}/{VAULT_DIR}/{stem}.txt", obligation_id=ob_id, reason=reason)
    if not (sc.data.get("disclosure") or {}).get("material_events"):
        manifest.add_absent(type="listed_event_notice", reason="disclosure.material_events is empty in the scenario")

    # 4. BONDI-format emission -------------------------------------------------------
    emission = events_mod.emit(sc.data)
    events_mod.write(emission, pack_root, envelope, manifest)
    events_mod.write_artifact_manifest(pack_root, envelope, manifest)

    # 5. manifest ----------------------------------------------------------------------
    saved = manifest.save()
    audit = _audit_pack(pack_root)
    if audit:
        raise PackError("pack audit failed after write: " + "; ".join(audit))
    return GenerateResult(
        deal_id=sc.deal_id,
        pack_root=pack_root,
        manifest_path=saved.path,
        manifest_sha256=saved.sha256,
        files_written=len(manifest.files),
        intake_files=len(files),
        vault_files=vault_written,
        absent_by_scenario=list(manifest.absent_by_scenario),
        intake_paths_unknown=list(sc.dropped_intake_paths),
    )


def cusip_like_tokens(text: str) -> list[str]:
    """CUSIP-shaped tokens in `text` (empty == clean).

    `law.CUSIP_NEAR_WORD_RE` is applied as is. `law.CUSIP_LIKE_STRICT_RE` (nine upper-alnum
    chars) also matches any nine-letter capital word -- `SYNTHETIC` in the legend -- so a
    strict match counts only when it carries at least one digit (a CUSIP's ninth character
    is a check digit; an all-letter token is never a CUSIP).
    """
    hits = [m.group(0) for m in law.CUSIP_NEAR_WORD_RE.finditer(text)]
    hits += [
        m.group(0)
        for m in law.CUSIP_LIKE_STRICT_RE.finditer(text)
        if any(ch.isdigit() for ch in m.group(0))
    ]
    return hits


def _audit_pack(pack_root: Path) -> list[str]:
    """Every file stamped, listed and clean; the platform token only where pinned."""
    from labkit.provenance import audit_file

    problems: list[str] = []
    listed = {e["path"]: e for e in PackManifest.load(pack_root)["files"]}
    on_disk = {p.relative_to(pack_root).as_posix() for p in pack_root.rglob("*") if p.is_file()}
    on_disk.discard(law.PACK_MANIFEST_NAME)
    for missing in sorted(set(listed) - on_disk):
        problems.append(f"manifest lists {missing} but it is not on disk")
    for orphan in sorted(on_disk - set(listed)):
        problems.append(f"{orphan} on disk but not in the manifest")
    for rel in sorted(on_disk & set(listed)):
        path = pack_root / rel
        if sha256_file(path) != listed[rel]["sha256"]:
            problems.append(f"{rel}: sha256 differs from the manifest")
        allowed, _ = _emma_allowance(rel)
        problems += [f"{rel}: {p}" for p in audit_file(path, emma_allowed=allowed)]
        text = path.read_text(encoding="utf-8")
        problems += [f"{rel}: CUSIP-like token {t!r}" for t in cusip_like_tokens(text)]
        if law.FORBIDDEN_SOURCES_RE.search(text):
            problems.append(f"{rel}: forbidden source token")
        for phrase in law.BLOCKLIST_PHRASES:
            if law.blocklist_hits(text, (phrase,)):
                problems.append(f"{rel}: blocklisted phrase {phrase!r}")
    return problems


